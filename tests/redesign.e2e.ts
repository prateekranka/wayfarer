import { test } from '@e2e-dev/mobile';
import { expect } from 'e2e';
import { tapControl, tapVisibleControl } from './controls.ts';

test('redesign preserves creation, choice, swipe, playback, style, refinement and export', async ({ app, screen, device }) => {
  await device.installApp();
  await app.open();
  await device.closeApp();
  await app.open();
  await expect(screen.getByTestId('create-montage')).toBeVisible();
  await app.screenshot('01-home');
  await tapVisibleControl(screen.getByTestId('create-montage'));
  await expect(screen.getByTestId('choose-photos')).toBeVisible();
  await expect(screen.getByTestId('choose-files')).toBeVisible();
  await app.screenshot('02-import');
  await tapVisibleControl(screen.getByTestId('sample-12'));
  await expect(screen.getByTestId('clip-count')).toContainText('12 clips');
  await app.screenshot('03-setup');
  await tapVisibleControl(screen.getByTestId('sample-music'));
  await expect(screen.getByTestId('make-reel')).toBeEnabled();
  for (const seconds of [15,30,15]) {
    await tapControl(screen, screen.getByTestId(`duration-${seconds}`), 'down', 'make-reel');
  }
  await tapControl(screen, screen.getByTestId('output-format'), 'down', 'make-reel');
  await tapVisibleControl(screen.getByText('1:1', { exact: true }));
  await tapControl(screen, screen.getByTestId('output-format'), 'down', 'make-reel');
  await tapVisibleControl(screen.getByText('9:16', { exact: true }));
  await tapControl(screen, screen.getByText('Creative controls', { exact: true }), 'down', 'make-reel');
  await expect(screen.getByRole('slider', 'Calm to Energetic')).toBeVisible();
  await app.screenshot('04-creative-controls');
  await tapVisibleControl(screen.getByTestId('make-reel'));
  await expect(screen.getByTestId('playback-state')).toContainText('Ready to play');
  await expect(screen.getByTestId('selected-edit-name')).toHaveText('Beat Sync · Balanced');
  await expect(screen.getByTestId('playback-position')).toContainText('/ 0:15');
  await expect(screen.getByTestId('playback-position')).toContainText(/^0:0[1-9] \/ /);
  await app.screenshot('05-balanced');
  await tapVisibleControl(screen.getByTestId('preview-play-pause'));
  await tapVisibleControl(screen.getByTestId('preview-mute'));
  await expect(screen.getByTestId('preview-mute')).toHaveValue('Muted');
  const frame = await screen.getByTestId('montage-player').boundingBox();
  if (!frame) throw new Error('Preview frame missing');
  await screen.swipe({ from: { x:frame.x+frame.width*.85,y:frame.y+frame.height*.45 }, to: { x:frame.x+frame.width*.15,y:frame.y+frame.height*.45 } });
  await expect(screen.getByTestId('selected-edit-name')).toHaveText('Beat Sync · Scenic');
  await expect(screen.getByTestId('playback-state')).toContainText('Ready to play');
  await expect(screen.getByTestId('preview-mute')).toHaveValue('Muted');
  await expect(screen.getByLabel('Play video', { exact:true })).toBeVisible();
  await app.screenshot('06-scenic-swiped');
  await tapVisibleControl(screen.getByTestId('preview-mute'));
  await tapVisibleControl(screen.getByTestId('variant-Beat Sync · Motion'));
  await expect(screen.getByTestId('selected-edit-name')).toHaveText('Beat Sync · Motion');
  await tapVisibleControl(screen.getByTestId('edit-style-info'));
  await expect(screen.getByText('What is Beat Sync?', { exact:true })).toBeVisible();
  await app.screenshot('07-style-info');
  await tapVisibleControl(screen.getByTestId('close-edit-info'));
  await tapVisibleControl(screen.getByTestId('teach-style'));
  await tapVisibleControl(screen.getByText('Preferences', { exact:true }));
  await expect(screen.getByTestId('taste-enabled')).toBeVisible();
  await tapVisibleControl(screen.getByText('References', { exact:true }));
  await expect(screen.getByTestId('reference-files')).toBeVisible();
  await app.screenshot('08-references');
  await tapVisibleControl(screen.getByTestId('close-my-style'));
  await tapVisibleControl(screen.getByTestId('refine-edit'));
  await tapVisibleControl(screen.getByTestId('lock-shot-0'));
  await expect(screen.getByTestId('locked-count')).toContainText('1 moments locked');
  await app.screenshot('09-refine');
  await tapVisibleControl(screen.getByTestId('lock-shot-0'));
  await expect(screen.getByTestId('locked-count')).toContainText('0 moments locked');
  await tapVisibleControl(screen.getByTestId('BackButton'));
  await tapVisibleControl(screen.getByTestId('export-montage'));
  await expect(screen.getByTestId('save-photos')).toBeVisible({ timeout:180000 });
  await expect(screen.getByTestId('export-edit-name')).toHaveText('Beat Sync · Motion');
  await expect(screen.getByTestId('preview-mute')).toHaveValue('Sound on');
  await app.screenshot('10-export');
});
