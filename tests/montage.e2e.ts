import { test } from '@e2e-dev/mobile';
import { expect } from 'e2e';
import { revealControl, tapControl, tapVisibleControl } from './controls.ts';

test('create, preview, replace, lock, regenerate, export and reopen a montage', async ({ app, screen, device }) => {
  if (process.env.WAYFARER_USE_INSTALLED !== '1') await device.installApp();
  await app.open();
  await device.closeApp();
  await device.setPermission('photos', 'grant');
  await app.open();
  await expect(screen.getByTestId('create-montage')).toBeVisible();
  await app.screenshot('home');
  await screen.getByTestId('create-montage').tap();
  await screen.getByTestId('sample-12').tap();
  await expect(screen.getByTestId('clip-count')).toContainText('12 clips', { timeout: 240_000 });
  await screen.getByTestId('sample-music').tap();
  await expect(screen.getByTestId('make-reel')).toBeEnabled({ timeout: 120_000 });
  await tapControl(screen, screen.getByTestId('duration-30'), 'down', 'make-reel');
  await tapControl(screen, screen.getByTestId('intent-beatSync'), 'down', 'make-reel');
  await app.screenshot('creative-direction');
  await screen.getByTestId('make-reel').tap();
  await expect(screen.getByTestId('montage-player')).toBeVisible({ timeout: 30_000 });
  await expect(screen.getByTestId('playback-state')).toContainText('Ready to play');
  await expect(screen.getByTestId('playback-position')).toContainText(/^0:(?:0[1-9]|[1-5][0-9]) \/ /);
  await app.screenshot('three-edits');
  for (const name of ['Beat Sync · Balanced', 'Beat Sync · Scenic', 'Beat Sync · Motion']) {
    const variant = screen.getByTestId('variant-' + name);
    await revealControl(screen, variant, 'down', 'export-montage');
    await expect(variant).toBeVisible();
    await tapVisibleControl(variant);
    await revealControl(screen, screen.getByTestId('montage-player'), 'up', 'export-montage');
    await expect(screen.getByTestId('playback-state')).toContainText('Ready to play');
    await expect(screen.getByTestId('playback-position')).toContainText(/^0:(?:0[1-9]|[1-5][0-9]) \/ /);
  }
  await tapControl(screen, screen.getByTestId('refine-edit'), 'down', 'export-montage');
  const previousSource = await screen.getByTestId('source-reference-0').textContent();
  await screen.getByTestId('replace-shot-0').tap();
  await expect(screen.getByTestId('alternative-0')).toBeVisible();
  const alternative = screen.getByTestId('alternative-0');
  const card = await alternative.boundingBox();
  const use = await alternative.getByText('Use this', { exact: true }).boundingBox();
  if (!card || !use) throw new Error('The replacement choice has no accessibility frame');
  await alternative.tap({ position: { x: use.x + use.width / 2 - card.x, y: use.y + use.height / 2 - card.y } });
  await expect(screen.getByTestId('source-reference-0')).not.toHaveText(previousSource ?? '');
  await screen.getByTestId('lock-shot-0').tap();
  await tapControl(screen, screen.getByTestId('lock-shot-1'), 'down', 'regenerate-with-locks');
  await revealControl(screen, screen.getByTestId('locked-count'), 'up', 'regenerate-with-locks');
  await expect(screen.getByTestId('locked-count')).toContainText('2 moments locked');
  await app.screenshot('locked-moments');
  await screen.getByTestId('regenerate-with-locks').tap();
  await expect(screen.getByTestId('locked-count')).toContainText('2 moments locked', { timeout: 120_000 });
  await app.back();
  await expect(screen.getByTestId('export-montage')).toBeVisible();
  await screen.getByTestId('export-montage').tap();
  await expect(screen.getByTestId('save-photos')).toBeVisible({ timeout: 180_000 });
  await app.screenshot('finished-export');
  await screen.getByTestId('save-photos').tap();
  await expect(screen.getByTestId('photos-saved')).toHaveText('Saved to Photos');
  await app.screenshot('saved-to-photos');
  await device.closeApp();
  await app.open();
  await expect(screen.getByTestId(/^project-card-/).first()).toBeVisible();
  await screen.getByTestId(/^project-card-/).first().tap();
  await expect(screen.getByTestId('montage-player')).toBeVisible();
  await tapControl(screen, screen.getByTestId('refine-edit'), 'down', 'export-montage');
  await expect(screen.getByTestId('locked-count')).toContainText('2 moments locked');
  await app.screenshot('reopened-project');
  await app.back();
  await app.back();
  await screen.getByTestId('create-montage').tap();
  await expect(screen.getByTestId('sample-12')).toBeVisible();
  await app.screenshot('create-after-saved-project');
});
