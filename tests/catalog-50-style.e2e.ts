import { expect } from 'e2e';
import { test } from './catalog.ts';
import { tapControl, tapVisibleControl } from './controls.ts';

// Run after the reel matrix has saved a reference from its first export.
test('catalog: learned style, approved example, reference notes and confirmations', async ({ app, screen, device, agent, capture }) => {
  await device.installApp();
  await app.open();
  await tapVisibleControl(screen.getByTestId(/^project-card-/).first());
  await expect(screen.getByTestId('playback-state')).toContainText('Ready to play');
  await tapControl(screen, screen.getByTestId('teach-style'), 'up', 'export-montage');
  await expect(screen.getByTestId('prefer-selected-edit')).toBeVisible();
  await capture('style-compare-generated-edits');
  await tapVisibleControl(screen.getByText('Watch selected edit', { exact: true }));
  await expect(screen.getByTestId('playback-state')).toContainText('Ready to play');
  await capture('style-comparison-video-preview');
  await tapVisibleControl(screen.getByTestId('close-comparison-preview'));
  const before = Number.parseInt((await screen.getByTestId('taste-feedback-count').textContent()) ?? '');
  if (!Number.isFinite(before)) throw new Error('Missing native feedback count');
  await tapVisibleControl(screen.getByTestId('prefer-selected-edit'));
  await expect(screen.getByTestId('taste-save-status')).toHaveText('Saved on this device');
  await capture('style-one-recorded-choice');
  await expect(screen.getByTestId('taste-feedback-count')).toContainText(`${before + 1} comparison${before === 0 ? '' : 's'} recorded`);
  await screen.scrollUntilVisible(screen.getByTestId('approve-edit-example'), { direction: 'down' });
  await tapVisibleControl(screen.getByTestId('approve-edit-example'));
  await capture('style-approved-example-saved');
  await tapVisibleControl(screen.getByText('Preferences', { exact: true }));
  await expect(screen.getByTestId('taste-enabled')).toBeVisible();
  await capture('style-preferences-learned');
  await tapVisibleControl(screen.getByTestId('taste-enabled'));
  await capture('style-learning-disabled');
  await tapVisibleControl(screen.getByTestId('taste-enabled'));
  await screen.scrollUntilVisible(screen.getByTestId('reset-taste'), { direction: 'down' });
  await tapVisibleControl(screen.getByTestId('reset-taste'));
  await capture('style-reset-confirmation');
  await tapVisibleControl(screen.getByText('Cancel', { exact: true }));
  await tapVisibleControl(screen.getByText('References', { exact: true }));
  await expect(screen.getByTestId(/^reference-[A-F0-9]/).first()).toBeVisible();
  await capture('style-references-populated');
  await screen.scrollUntilVisible(screen.getByTestId(/^approved-example-/).first(), { direction: 'down' });
  await tapVisibleControl(screen.getByTestId(/^approved-example-/).first());
  await expect(screen.getByText('Approved source ranges', { exact: true })).toBeVisible();
  await capture('style-approved-example-source-ranges');
  await screen.scrollUntilVisible(screen.getByText('Remove example', { exact: true }), { direction: 'down' });
  await tapVisibleControl(screen.getByText('Remove example', { exact: true }));
  await capture('style-remove-example-confirmation');
  await tapVisibleControl(screen.getByText('Cancel', { exact: true }));
  await app.back();
  await tapVisibleControl(screen.getByText('Preferences', { exact: true }));
  await tapVisibleControl(screen.getByText('References', { exact: true }));
  await tapVisibleControl(screen.getByTestId(/^reference-[A-F0-9]/).first());
  await expect(screen.getByTestId('file-player')).toBeVisible();
  await capture('reference-detail-player');
  await screen.scrollUntilVisible(screen.getByTestId('reference-note'), { direction: 'down' });
  await expect(screen.getByTestId('save-reference-note')).not.toBeEnabled();
  await capture('reference-empty-note');
  await tapVisibleControl(screen.getByTestId('reference-note'));
  await agent.act('Type into the focused reference note', { params: { text: 'Hold the scenery before changing scenes. Đà Nẵng was worth the wait 🌅' } });
  await expect(screen.getByTestId('reference-note')).toHaveValue('Hold the scenery before changing scenes. Đà Nẵng was worth the wait 🌅');
  await capture('reference-note-keyboard-and-unicode');
  await tapVisibleControl(screen.getByTestId('close-note-keyboard'));
  await tapVisibleControl(screen.getByTestId('save-reference-note'));
  await expect(screen.getByText('Hold the scenery before changing scenes. Đà Nẵng was worth the wait 🌅', { exact: true })).toBeVisible();
  await capture('reference-saved-timestamp-note');
  await app.back();
  await expect(screen.getByTestId(/^reference-[A-F0-9]/).first()).toContainText('1 note');
  await capture('style-reference-list-one-note');
  await tapVisibleControl(screen.getByTestId(/^reference-[A-F0-9]/).first());
  await expect(screen.getByTestId('file-player')).toBeVisible();
  await screen.scrollUntilVisible(screen.getByText('Estimated pacing', { exact: true }), { direction: 'down' });
  await capture('reference-estimated-pacing');
  const pacing = screen.getByTestId('use-reference-pacing');
  if (await pacing.isVisible() && await pacing.isEnabled()) {
    await tapVisibleControl(pacing);
    await expect(screen.getByText(/Pacing preference saved for future/)).toBeVisible();
    await capture('reference-pacing-preference-saved');
  }
  await screen.scrollUntilVisible(screen.getByText('Remove reference reel', { exact: true }), { direction: 'down' });
  await tapVisibleControl(screen.getByText('Remove reference reel', { exact: true }));
  await capture('reference-remove-confirmation');
  await tapVisibleControl(screen.getByText('Cancel', { exact: true }));
  await app.back();
  await tapVisibleControl(screen.getByTestId('close-my-style'));
  await device.closeApp();
  await app.open();
  await tapVisibleControl(screen.getByTestId('open-my-style'));
  await tapVisibleControl(screen.getByText('References', { exact: true }));
  await tapVisibleControl(screen.getByTestId(/^reference-[A-F0-9]/).first());
  await screen.scrollUntilVisible(screen.getByText('Hold the scenery before changing scenes. Đà Nẵng was worth the wait 🌅', { exact: true }), { direction: 'down' });
  await capture('reference-saved-note-after-relaunch');
});
